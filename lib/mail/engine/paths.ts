import { mkdirSync } from "node:fs";
import path from "node:path";

// Everything the mail engine writes to disk lives under one directory. The CMS
// keeps only metadata in PostgreSQL; message bodies are files, which keeps the
// database small and makes backup/restore of mail a plain file copy.

export function mailDataDir(): string {
    const configured = process.env.MAIL_DATA_DIR;
    return configured && configured.trim() ? path.resolve(configured) : path.resolve(process.cwd(), "data", "mail");
}

export function ensureDir(dir: string): string {
    mkdirSync(dir, { recursive: true });
    return dir;
}

// Resolve a stored relative path inside the data directory, refusing anything
// that would escape it. Stored paths are always generated by us, so a value
// outside the root means the row was tampered with.
export function resolveStored(relative: string): string {
    const root = mailDataDir();
    const full = path.resolve(root, relative);
    if (full !== root && !full.startsWith(root + path.sep))
        throw new Error("Refusing to access a path outside the mail data directory.");
    return full;
}

export function relativeFromAbsolute(absolute: string): string {
    const root = mailDataDir();
    const rel = path.relative(root, absolute);
    if (rel.startsWith("..") || path.isAbsolute(rel))
        throw new Error("Mail file is outside the data directory.");
    return rel.split(path.sep).join("/");
}

// A fresh message path: accounts/<id>/<year>/<month>/<uuid>.eml
export function messagePath(accountId: number, id: string): { absolute: string; relative: string } {
    const d = new Date();
    const year = String(d.getUTCFullYear());
    const month = String(d.getUTCMonth() + 1).padStart(2, "0");
    const dir = ensureDir(path.join(mailDataDir(), "accounts", String(accountId), year, month));
    const absolute = path.join(dir, `${id}.eml`);
    return { absolute, relative: relativeFromAbsolute(absolute) };
}
