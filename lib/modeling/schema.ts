// Additive field-driven schema. Existing base tables are not modified except
// for a nullable moderation column on `revisions`. All statements are idempotent.

export const MODELING_SCHEMA = `
CREATE TABLE IF NOT EXISTS model_content_types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  machine_name TEXT UNIQUE NOT NULL,
  label TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  base_type TEXT NOT NULL DEFAULT 'custom',
  entity_type TEXT NOT NULL DEFAULT 'custom',
  workflow_id INTEGER,
  position INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS model_fields (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_type_id INTEGER NOT NULL,
  machine_name TEXT NOT NULL,
  label TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  field_type TEXT NOT NULL DEFAULT 'text',
  cardinality INTEGER NOT NULL DEFAULT 1,
  required INTEGER NOT NULL DEFAULT 0,
  settings TEXT NOT NULL DEFAULT '{}',
  position INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  UNIQUE (content_type_id, machine_name)
);
CREATE INDEX IF NOT EXISTS idx_model_fields_type ON model_fields(content_type_id);

CREATE TABLE IF NOT EXISTS model_entity_bundles (
  entity_table TEXT NOT NULL,
  entity_type TEXT NOT NULL DEFAULT '',
  entity_id INTEGER NOT NULL,
  content_type_id INTEGER NOT NULL,
  created_at TEXT NOT NULL,
  PRIMARY KEY (entity_table, entity_id)
);
CREATE INDEX IF NOT EXISTS idx_dc_bundle_type ON model_entity_bundles(content_type_id);

CREATE TABLE IF NOT EXISTS model_field_values (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_table TEXT NOT NULL,
  entity_type TEXT NOT NULL DEFAULT '',
  entity_id INTEGER NOT NULL,
  field_id INTEGER NOT NULL,
  delta INTEGER NOT NULL DEFAULT 0,
  value TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL,
  UNIQUE (entity_table, entity_id, field_id, delta)
);
CREATE INDEX IF NOT EXISTS idx_dc_values_entity ON model_field_values(entity_table, entity_id);
CREATE INDEX IF NOT EXISTS idx_dc_values_field ON model_field_values(field_id);

CREATE TABLE IF NOT EXISTS model_workflows (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  machine_name TEXT UNIQUE NOT NULL,
  label TEXT NOT NULL,
  initial_state TEXT NOT NULL DEFAULT 'draft',
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS model_workflow_states (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_id INTEGER NOT NULL,
  state TEXT NOT NULL,
  label TEXT NOT NULL,
  weight INTEGER NOT NULL DEFAULT 0,
  published INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  UNIQUE (workflow_id, state)
);
CREATE INDEX IF NOT EXISTS idx_dc_wf_states_workflow ON model_workflow_states(workflow_id);

CREATE TABLE IF NOT EXISTS model_workflow_transitions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_id INTEGER NOT NULL,
  from_state TEXT NOT NULL,
  to_state TEXT NOT NULL,
  label TEXT NOT NULL,
  weight INTEGER NOT NULL DEFAULT 0,
  min_role TEXT NOT NULL DEFAULT 'editor',
  created_at TEXT NOT NULL,
  UNIQUE (workflow_id, from_state, to_state)
);
CREATE INDEX IF NOT EXISTS idx_dc_wf_trans_workflow ON model_workflow_transitions(workflow_id);

CREATE TABLE IF NOT EXISTS model_config_snapshots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL,
  data TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS model_views (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  machine_name TEXT UNIQUE NOT NULL,
  label TEXT NOT NULL,
  base TEXT NOT NULL DEFAULT 'posts',
  display TEXT NOT NULL DEFAULT 'list',
  query TEXT NOT NULL DEFAULT '{}',
  fields TEXT NOT NULL DEFAULT '[]',
  filters TEXT NOT NULL DEFAULT '[]',
  sorts TEXT NOT NULL DEFAULT '[]',
  pager TEXT NOT NULL DEFAULT '{"type":"full","per_page":10}',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
`;