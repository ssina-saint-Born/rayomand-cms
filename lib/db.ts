async function query(text: string, values: unknown[]) {
    await initialize();
    return (context.getStore() ?? pool()).query(text, values);
}
const database = {
    async one(text: string, ...values: unknown[]): Promise<any> { return (await query(text, values)).rows[0]; },
    async many(text: string, ...values: unknown[]): Promise<any[]> { return (await query(text, values)).rows; },
    async execute(text: string, ...values: unknown[]): Promise<{
        id: number;
        changes: number;
    }> {
        const result = await query(text, values);
        return { id: result.rows[0]?.id, changes: result.rowCount ?? 0 };
    },
};
export function getDb() { return database; }
export function now(): string { return new Date().toISOString(); }
export async function withTransaction<T>(work: () => Promise<T>): Promise<T> {
    await initialize();
    if (context.getStore())
        return work();
    const client = await pool().connect();
    try {
        await client.query("BEGIN");
        const result = await context.run(client, work);
        await client.query("COMMIT");
        return result;
    }
    catch (error) {
        await client.query("ROLLBACK");
        throw error;
    }
    finally {
        client.release();
    }
}
